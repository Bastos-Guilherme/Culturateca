create index idx_curator_location
    on curator(location);

create index idx_location_parent
    on location(location);

create index idx_location_curator
    on location(curator);

create index idx_canonic_category
    on canonic(category);

create index idx_copy_canonic
    on copy(canonic);

create index idx_copy_location
    on copy(location);

create index idx_collection_curator
    on collection(curator);

create index idx_collection_copy_copy
    on collection_copy(copy);

create index idx_pending_curator_location
    on pending_curator(location);

