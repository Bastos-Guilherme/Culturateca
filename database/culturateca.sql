create table property (
    id bigserial primary key,
    name varchar(255) not null
);

create table category (
    id bigserial primary key,
    name varchar(255) not null
);

create table curator (
    id bigserial primary key,
    email varchar(255) not null unique,
    location bigint,
    password varchar(255) not null,
    name varchar(255) not null,
    gender varchar(255),
    phone varchar(255),
    ispublic boolean,
    bio text,
    following jsonb,
    profilepicture varchar(255),
    emailmfaenabled boolean not null default false
);

create table location (
    id bigserial primary key,
    name varchar(255) not null,
    latitude double precision,
    longitude double precision,
    location bigint,
    curator bigint
);

alter table curator
    add constraint fk_curator_location
    foreign key (location)
    references location(id)
    on delete set null;

alter table location
    add constraint fk_location_parent
    foreign key (location)
    references location(id)
    on delete set null;

alter table location
    add constraint fk_location_curator
    foreign key (curator)
    references curator(id)
    on delete set null;

create table canonic (
    id bigserial primary key,
    name varchar(255) not null,
    property jsonb not null,
    category bigint references category(id)
);

create table copy (
    id bigserial primary key,
    name varchar(255),
    property jsonb not null,
    canonic bigint references canonic(id),
    location bigint references location(id)
);

create table collection (
    id bigserial primary key,
    curator bigint references curator(id),
    name varchar(255) not null,
    ispublic boolean
);

create table collection_copy (
    collection bigint references collection(id) on delete cascade,
    copy bigint references copy(id) on delete cascade,
    primary key (collection, copy)
);

create table pending_curator (
    id bigint generated by default as identity primary key,
    email varchar(255) not null unique,
    name varchar(255) not null,
    password varchar(255) not null,
    gender varchar(50),
    phone varchar(255),
    ispublic boolean not null default true,
    bio text,
    profilepicture varchar(255),
    following jsonb,
    location bigint,
    code_hash varchar(255) not null,
    expires_at timestamp with time zone not null,
    last_sent_at timestamp with time zone not null,
    attempts integer not null default 0,

    constraint fk_pending_curator_location
        foreign key (location)
        references location(id)
        on delete set null,

    constraint chk_pending_curator_attempts
        check (attempts >= 0)
);

create index idx_pending_curator_expires_at
    on pending_curator(expires_at);

create table pending_login_verification (
    id varchar(36) primary key,
    email varchar(255) not null unique,
    code_hash varchar(255) not null,
    expires_at timestamp with time zone not null,
    attempts integer not null default 0,
    created_at timestamp with time zone not null,

    constraint chk_pending_login_attempts
        check (attempts >= 0)
);

create index idx_pending_login_expires_at
    on pending_login_verification(expires_at);

create index idx_curator_location
    on curator(location);

create index idx_location_parent
    on location(location);

create index idx_location_curator
    on location(curator);

create index idx_canonic_category
    on canonic(category);

create index idx_copy_canonic
    on copy(canonic);

create index idx_copy_location
    on copy(location);

create index idx_collection_curator
    on collection(curator);

create index idx_collection_copy_copy
    on collection_copy(copy);

create index idx_pending_curator_location
    on pending_curator(location);